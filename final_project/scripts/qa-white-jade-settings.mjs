import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';

const out = path.resolve('docs/ui-qa-2026-11-08/final');
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:5181/?islandSeed=684#/atlas/wonderland-terrain', { waitUntil: 'domcontentloaded' });
await page.locator('.exhibit-cameras').waitFor({ timeout: 60000 });
await page.getByRole('button', { name: 'Creature' }).click();
await page.waitForTimeout(2600);
await page.getByRole('button', { name: 'Settings' }).click();
await page.screenshot({ path: path.join(out, 'settings-top.png') });
const drawer = page.locator('.exhibit-drawer-body');
await drawer.evaluate(el => { el.scrollTop = el.scrollHeight; });
await page.screenshot({ path: path.join(out, 'settings-bottom.png') });
await page.locator('details.exhibit-panel-section').filter({ hasText: 'Shape the island' }).locator('summary').first().click();
await page.screenshot({ path: path.join(out, 'settings-shape.png') });
await page.locator('details.exhibit-panel-section').filter({ hasText: 'Shape the island' }).locator('summary').first().click();
await page.locator('details.exhibit-panel-section').filter({ hasText: 'Debug & performance' }).locator('summary').first().click();
await page.getByText('Show creature path & footprints', { exact: true }).click();
await page.waitForFunction(() => document.querySelector('.exhibit-creature-now')?.textContent?.includes('walking'), undefined, { timeout: 60000 });
await drawer.evaluate(el => { el.scrollTop = el.scrollHeight; });
await page.screenshot({ path: path.join(out, 'debug-on.png') });
const legendOn = await page.locator('.exhibit-legend').count();
await page.getByText('Show creature path & footprints', { exact: true }).click();
await page.waitForTimeout(250);
await page.screenshot({ path: path.join(out, 'debug-off.png') });
const legendOff = await page.locator('.exhibit-legend').count();
console.log({ legendOn, legendOff });
await drawer.evaluate(el => { el.scrollTop = 0; });
await page.getByRole('button', { name: 'Meet the creature' }).click();
await page.locator('.resource-atlas.has-detail').waitFor();
await page.screenshot({ path: path.join(out, 'meet-creature-detail.png') });
console.log('Meet the creature opened resource atlas detail');
await browser.close();
