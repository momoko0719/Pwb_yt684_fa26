import { chromium } from 'playwright';
import path from 'node:path';
import fs from 'node:fs';

const out = path.resolve(process.argv[2] ?? 'docs/ui-qa-2026-11-08/final');
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:5181/?islandSeed=684#/atlas/wonderland-terrain', { waitUntil: 'domcontentloaded' });
await page.locator('.exhibit-cameras').waitFor({ timeout: 60000 });
await page.getByRole('button', { name: 'Creature' }).first().click();
await page.waitForTimeout(3200);
await page.screenshot({ path: path.join(out, 'follow-before-drag.png') });
await page.mouse.move(690, 455);
await page.mouse.down();
await page.mouse.move(910, 400, { steps: 12 });
await page.mouse.up();
await page.screenshot({ path: path.join(out, 'follow-after-drag.png') });
await page.waitForTimeout(2500);
await page.screenshot({ path: path.join(out, 'follow-after-wait.png') });
await page.getByRole('button', { name: 'Mountains' }).click();
await page.waitForTimeout(2600);
await page.screenshot({ path: path.join(out, 'follow-other-chapter.png') });
await page.getByRole('button', { name: 'Settings' }).click();
await page.getByText('Walk', { exact: true }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: path.join(out, 'follow-walk.png') });
console.log('drag, other chapter, Walk: page screenshots captured');
await browser.close();
