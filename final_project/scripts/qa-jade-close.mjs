import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text().slice(0, 300)); });
await page.goto('http://localhost:5181/?islandSeed=684#/atlas/wonderland-terrain');
await page.locator('.exhibit-cameras').waitFor({ timeout: 60000 });
await page.waitForTimeout(34000);
await page.getByRole('button', { name: 'Water' }).click();
await page.waitForTimeout(3000);
await page.mouse.move(650, 580);
await page.mouse.wheel(0, -620);
await page.waitForTimeout(1400);
await page.screenshot({ path: 'docs/equilinox-pass-2026-11-14/pool-close.png' });
await page.getByRole('button', { name: 'Water' }).click();
await page.waitForTimeout(2500);
await page.mouse.move(305, 770);
await page.mouse.wheel(0, -570);
await page.waitForTimeout(1400);
await page.screenshot({ path: 'docs/equilinox-pass-2026-11-14/bend-close.png' });
console.log(JSON.stringify({ errors }));
await browser.close();
